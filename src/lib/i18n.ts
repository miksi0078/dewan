const dict: Record<Lang, Dict> = { en, ps, pr };

export function t(lang: Lang, key: string): string {
  return dict[lang]?.[key] ?? dict.en[key] ?? key;
}

/** Returns obj[`${field}_${lang}`], falling back to Pashto script, Roman, then English. */
export function pick(obj: any, field: string, lang: Lang): string {
  if (!obj) return '';
  const order: Lang[] = [lang, 'ps', 'pr', 'en'];
  for (const l of order) {
    const v = obj[`${field}_${l}`];
    if (typeof v === 'string' && v.trim() !== '') return v;
  }
  return '';
}

/** Which language the picked value actually came from (for correct text direction). */
export function pickLang(obj: any, field: string, lang: Lang): Lang {
  if (!obj) return lang;
  const order: Lang[] = [lang, 'ps', 'pr', 'en'];
  for (const l of order) {
    const v = obj[`${field}_${l}`];
    if (typeof v === 'string' && v.trim() !== '') return l;
  }
  return lang;
}
